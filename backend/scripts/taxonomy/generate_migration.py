#!/usr/bin/env python3
"""Generate the tag-dictionary Flyway migration from tags.txt.

IDs are uuid5(namespace, full path) so re-running is stable and the migration stays idempotent.
Usage: python3 backend/scripts/taxonomy/generate_migration.py [output.sql]
"""
import re
import sys
import uuid
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE = HERE / "tags.txt"
DEFAULT_OUT = HERE.parents[1] / "src/main/resources/db/migration/V4__curated_tag_taxonomy.sql"
NAMESPACE = uuid.uuid5(uuid.NAMESPACE_URL, "https://connectionsbetween.us/tags")
SEP = " › "

LINE = re.compile(r"^(?P<indent> *)(?P<label>[^{]+?)\s*(?:\{(?P<flags>[^}]*)\})?\s*$")


def parse():
    nodes, stack = [], []  # stack of (depth, node)
    for n, raw in enumerate(SOURCE.read_text(encoding="utf-8").splitlines(), 1):
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        m = LINE.match(raw)
        if not m or len(m["indent"]) % 2:
            sys.exit(f"tags.txt:{n}: bad line or indentation: {raw!r}")
        depth = len(m["indent"]) // 2
        flags = {}
        for part in filter(None, (p.strip() for p in (m["flags"] or "").split(","))):
            key, _, value = part.partition("=")
            flags[key] = value or True
        while stack and stack[-1][0] >= depth:
            stack.pop()
        if depth and (not stack or stack[-1][0] != depth - 1):
            sys.exit(f"tags.txt:{n}: indentation skips a level")
        parent = stack[-1][1] if stack else None
        label = m["label"].strip()
        path = f"{parent['path']}{SEP}{label}" if parent else label
        node = {
            "id": str(uuid.uuid5(NAMESPACE, path)),
            "label": label,
            "path": path,
            "parent": parent,
            "level": depth + 1,
            "root": parent["root"] if parent else label,
            "icon": flags.get("icon") if not parent else None,
            "self_only": "self" in flags,
            "single": "single" in flags,
            "order": 0,
        }
        siblings = [x for x in nodes if x["parent"] is parent]
        node["order"] = len(siblings) + 1
        if any(s["label"].lower() == label.lower() for s in siblings):
            sys.exit(f"tags.txt:{n}: duplicate sibling {label!r}")
        nodes.append(node)
        stack.append((depth, node))
    return nodes


def q(value):
    return "NULL" if value is None else "'" + str(value).replace("'", "''") + "'"


def render(nodes):
    rows = ",\n".join(
        f"({q(x['id'])}, {q(x['root'])}, {q(x['label'])}, {q(x['parent']['id'] if x['parent'] else None)}, "
        f"{x['level']}, {q(x['icon'])}, {x['order']}, {str(x['self_only']).upper()}, {str(x['single']).upper()})"
        for x in nodes
    )
    ids = ",\n".join(f"({q(x['id'])})" for x in nodes)
    return f"""-- V4__curated_tag_taxonomy.sql: GENERATED by backend/scripts/taxonomy/generate_migration.py from tags.txt.
-- Do not edit by hand. Replaces the V3 career-only seed with the curated category taxonomy.
-- Existing assignments that point at retired dictionary tags are preserved as custom labels.

-- 1. Category rules
ALTER TABLE tags ADD COLUMN IF NOT EXISTS self_only BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE tags ADD COLUMN IF NOT EXISTS single_select BOOLEAN NOT NULL DEFAULT FALSE;

-- 2. Upsert the curated tree (parents always precede children)
INSERT INTO tags (id, category, label, parent_id, level, icon, display_order, self_only, single_select) VALUES
{rows}
ON CONFLICT (id) DO UPDATE SET
    category = EXCLUDED.category,
    label = EXCLUDED.label,
    parent_id = EXCLUDED.parent_id,
    level = EXCLUDED.level,
    icon = EXCLUDED.icon,
    display_order = EXCLUDED.display_order,
    self_only = EXCLUDED.self_only,
    single_select = EXCLUDED.single_select;

DROP TABLE IF EXISTS curated_tag_ids;
CREATE TEMP TABLE curated_tag_ids (id UUID PRIMARY KEY);
INSERT INTO curated_tag_ids (id) VALUES
{ids};

-- 3. Keep assignments to retired tags as custom labels (label + old category preserved)
UPDATE user_tags ut
SET custom_label = t.label,
    custom_category = COALESCE(ut.custom_category, t.category),
    tag_id = NULL
FROM tags t
WHERE ut.tag_id = t.id
  AND t.id NOT IN (SELECT id FROM curated_tag_ids);

UPDATE user_tags ut
SET custom_category = COALESCE(ut.custom_category, t.label),
    parent_tag_id = NULL
FROM tags t
WHERE ut.parent_tag_id = t.id
  AND t.id NOT IN (SELECT id FROM curated_tag_ids);

-- 4. Retire everything not in the curated tree
DELETE FROM tags WHERE id NOT IN (SELECT id FROM curated_tag_ids);

DROP TABLE curated_tag_ids;
"""


if __name__ == "__main__":
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_OUT
    nodes = parse()
    out.write_text(render(nodes), encoding="utf-8")
    roots = [x for x in nodes if x["level"] == 1]
    print(f"{len(nodes)} nodes ({len(roots)} categories) -> {out}")

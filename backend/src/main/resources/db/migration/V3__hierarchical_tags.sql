-- V3__hierarchical_tags.sql: Support hierarchical multi-tier tags and seed initial curated taxonomy

-- 1. Alter tags table for hierarchy support
ALTER TABLE tags ADD COLUMN IF NOT EXISTS parent_id UUID REFERENCES tags(id) ON DELETE CASCADE;
ALTER TABLE tags ADD COLUMN IF NOT EXISTS level INT NOT NULL DEFAULT 1;
ALTER TABLE tags ADD COLUMN IF NOT EXISTS icon VARCHAR(50);
ALTER TABLE tags ADD COLUMN IF NOT EXISTS display_order INT DEFAULT 0;

CREATE INDEX IF NOT EXISTS idx_tags_parent ON tags(parent_id);
CREATE INDEX IF NOT EXISTS idx_tags_level ON tags(level);

-- 2. Alter user_tags table for parent tag and contextual custom category support
ALTER TABLE user_tags ADD COLUMN IF NOT EXISTS parent_tag_id UUID REFERENCES tags(id) ON DELETE SET NULL;
ALTER TABLE user_tags ADD COLUMN IF NOT EXISTS custom_category VARCHAR(255);
CREATE INDEX IF NOT EXISTS idx_user_tags_parent ON user_tags(parent_tag_id);

-- Drop old unique constraint on category + label if exists to allow same label under different parent categories
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'uq_tags_category_label') THEN
        ALTER TABLE tags DROP CONSTRAINT uq_tags_category_label;
    END IF;
END $$;


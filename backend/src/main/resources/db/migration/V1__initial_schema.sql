-- V1__initial_schema.sql: Initial baseline schema matching all JPA entities

-- 1. Neighborhoods table
CREATE TABLE IF NOT EXISTS neighborhoods (
    curve_index BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_count BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE
);

-- 2. Users table
CREATE TABLE IF NOT EXISTS users (
    id UUID PRIMARY KEY,
    first_name VARCHAR(255),
    last_name VARCHAR(255),
    phone_number VARCHAR(255) NOT NULL UNIQUE,
    invite_code VARCHAR(255) NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    bio VARCHAR(2000),
    max_connection_degree INTEGER,
    default_user BOOLEAN NOT NULL DEFAULT FALSE,
    neighborhood_curve_index BIGINT NOT NULL REFERENCES neighborhoods(curve_index),
    local_index BIGINT,
    map_index BIGINT,
    map_x BIGINT,
    map_y BIGINT
);

CREATE INDEX IF NOT EXISTS idx_users_map_index ON users(map_index);

-- 3. Connections table (undirected edges)
CREATE TABLE IF NOT EXISTS connections (
    id UUID PRIMARY KEY,
    user_a_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    user_b_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_connections_a_b UNIQUE (user_a_id, user_b_id)
);

CREATE INDEX IF NOT EXISTS idx_connections_user_a ON connections(user_a_id);
CREATE INDEX IF NOT EXISTS idx_connections_user_b ON connections(user_b_id);

-- 4. Auth tokens table
CREATE TABLE IF NOT EXISTS auth_tokens (
    id UUID PRIMARY KEY,
    token VARCHAR(255) NOT NULL UNIQUE,
    user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    expires_at TIMESTAMP WITH TIME ZONE
);

CREATE INDEX IF NOT EXISTS idx_auth_tokens_token ON auth_tokens(token);
CREATE INDEX IF NOT EXISTS idx_auth_tokens_user_id ON auth_tokens(user_id);

-- 5. Connection requests table
CREATE TABLE IF NOT EXISTS connection_requests (
    id UUID PRIMARY KEY,
    sender_id UUID REFERENCES users(id) ON DELETE CASCADE,
    receiver_id UUID REFERENCES users(id) ON DELETE CASCADE,
    status VARCHAR(50)
);

CREATE INDEX IF NOT EXISTS idx_connection_requests_sender ON connection_requests(sender_id);
CREATE INDEX IF NOT EXISTS idx_connection_requests_receiver ON connection_requests(receiver_id);

-- 6. OTPs table
CREATE TABLE IF NOT EXISTS otps (
    id UUID PRIMARY KEY,
    phone_number VARCHAR(255) NOT NULL,
    code VARCHAR(255) NOT NULL,
    expires_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_otps_phone_number ON otps(phone_number);

-- 7. Tags dictionary table
CREATE TABLE IF NOT EXISTS tags (
    id UUID PRIMARY KEY,
    category VARCHAR(255),
    label VARCHAR(255),
    CONSTRAINT uq_tags_category_label UNIQUE (category, label)
);

-- 8. User tags mapping table
CREATE TABLE IF NOT EXISTS user_tags (
    id UUID PRIMARY KEY,
    tagger_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    subject_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    tag_id UUID REFERENCES tags(id) ON DELETE CASCADE,
    custom_label VARCHAR(255),
    CONSTRAINT uq_user_tags_tagger_subject_tag UNIQUE (tagger_id, subject_id, tag_id)
);

CREATE INDEX IF NOT EXISTS idx_user_tags_subject ON user_tags(subject_id);
CREATE INDEX IF NOT EXISTS idx_user_tags_tagger ON user_tags(tagger_id);

-- 9. User notes table
CREATE TABLE IF NOT EXISTS user_notes (
    id UUID PRIMARY KEY,
    author_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    subject_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    content TEXT,
    CONSTRAINT uq_user_notes_author_subject UNIQUE (author_id, subject_id)
);

CREATE INDEX IF NOT EXISTS idx_user_notes_author ON user_notes(author_id);
CREATE INDEX IF NOT EXISTS idx_user_notes_subject ON user_notes(subject_id);
